VERSION='5.3.0-research-multicloud.2'
def sha(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()
def write_json(p,x): Path(p).write_text(json.dumps(x,indent=2,allow_nan=False)+'\n')
def grid_load(path, recipe_path):
    grid = load_json(path)
    recipe = load_json(recipe_path)
    resolve_grid(grid, recipe)
    if grid.get('confirmed') is not True or 'input_contract' not in grid:
        raise ValueError('use a run grid generated by matrix intake')
    return grid

def manifest_science(manifest):
    return manifest.get('resolved_science') or resolved_science(manifest.get('grid', {'configs':[{'config_id':'default'}], 'baseline_config_id':'default'}))


def prepare(a):
    grid = grid_load(a.grid, a.recipe)
    source = load_json(a.source_manifest)
    staged = {'bin/research.py': Path(__file__), 'bin/freeze5_scoring.py': Path('freeze5_scoring.py'),
              'bin/matrix_intake.py': Path('matrix_intake.py'), 'conf/recipe.json': Path(a.recipe)}
    staged['bin/science_config.py']=Path('science_config.py')
    for path in Path('dimple_representations').glob('*.py'):
        staged['bin/dimple_representations/'+path.name]=path
    for name, path in staged.items():
        if source.get(name) != sha(path):
            raise ValueError(f'staged source checksum mismatch: {name}')
    science = resolved_science(grid)
    contract = grid['input_contract']
    ids, values = verify_input(a.input, contract)
    matrix = np.asarray(values, dtype=np.float64)
    if contract['orientation'] == 'features_by_objects':
        matrix = matrix.T
    np.save('pixels.npy', matrix)
    pd.DataFrame({'object_id': ids}).to_csv('object_ids.csv', index=False)
    write_json('manifest.json', {
        'version': VERSION, 'input_sha256': contract['sha256'], 'run_grid_sha256': sha(a.grid),
        'input_contract': contract, 'matrix_shape': list(matrix.shape), 'scaling': 'none',
        'pixels_sha256': sha('pixels.npy'), 'object_ids_sha256': sha('object_ids.csv'),
        'image': a.image, 'grid': grid, 'resolved_science': science, 'seed_sequence': science['seeds'],
        'hdbscan': {**science['hdbscan'], **science['hdbscan_parameters']},
        'source_checksums': source, 'scientific_acceptance': False,
    })

def seeds(a):
 import umap
 g=grid_load(a.grid,a.recipe); science=resolved_science(g); c=next(c for c in science['configs'] if c['config_id']==a.config)
 x=np.load(a.pixels,allow_pickle=False); values=[]
 lineage=sha(a.manifest); prepared=load_json(a.manifest)
 if (list(x.shape)!=prepared['matrix_shape'] or sha(a.grid)!=prepared['run_grid_sha256']
     or sha(a.pixels)!=prepared['pixels_sha256']):
  raise ValueError('seed matrix or grid differs from PREPARE')
 if not 1<=a.start<=a.end<=len(science['seeds'][a.config]): raise ValueError('Invalid seed interval')
 for s in range(a.start,a.end+1):
  t=time.monotonic(); parameters={k:v for k,v in c.items() if k!='config_id'}
  if science['backend']=='umap':
   parameters['random_state']=science['seeds'][a.config][s-1]
   v=umap.UMAP(**parameters,n_jobs=1).fit_transform(x).astype(np.float32)
   if v.shape!=(x.shape[0],c['n_components']): raise ValueError('Invalid UMAP dimensions')
  else:
   from dimple_representations.pca_runner import fit_pca
   from dimple_representations.ica_runner import fit_ica
   result=(fit_pca if science['backend']=='pca' else fit_ica)(x,parameters)
   v=result['embedding']
   write_json(f'{a.config}.representation.json',{'parameters':result['parameters'],'diagnostics':result['diagnostics']})
   np.savez_compressed(f'{a.config}.representation.npz',**result['arrays'])
  if v.ndim!=2 or v.shape[0]!=x.shape[0] or not np.isfinite(v).all(): raise ValueError('Invalid representation output')
  values.append(v); print(json.dumps({'seed':science['seeds'][a.config][s-1],'seconds':time.monotonic()-t}),flush=True)
 np.savez_compressed(f'{a.config}.seeds-{a.start:04d}-{a.end:04d}.npz',seeds=np.arange(a.start,a.end+1),
                     embedding=np.stack(values),config_id=a.config,run_sha256=lineage)

def concat(a):
 prepared=load_json(a.manifest); count=prepared['matrix_shape'][0]
 science=manifest_science(prepared); repetitions=len(science['seeds'].get(a.config, list(range(1,1001)))); dimensions=None
 lineage=sha(a.manifest)
 paths=sorted(Path('.').glob(f'{a.config}.seeds-*.npz')); seen={}
 for p in paths:
  with np.load(p,allow_pickle=False) as z:
   seed_ids=z['seeds']; embeddings=z['embedding']
   if z['config_id'].item()!=a.config or z['run_sha256'].item()!=lineage:
    raise ValueError('seed chunk belongs to a different run or configuration')
   if dimensions is None:
    dimensions=next((c['n_components'] for c in science['configs'] if c['config_id']==a.config),3) if science['backend']=='umap' else embeddings.shape[-1]
   if (seed_ids.ndim!=1 or seed_ids.dtype.kind not in 'iu' or not len(seed_ids) or
       embeddings.shape!=(len(seed_ids),count,dimensions) or embeddings.dtype!=(np.float32 if science['backend']=='umap' else np.float64) or not np.isfinite(embeddings).all()):
    raise ValueError('seed IDs and float32 embeddings must have exact matching shapes')
   if not np.array_equal(seed_ids,np.arange(int(seed_ids[0]),int(seed_ids[0])+len(seed_ids))) or p.name!=f'{a.config}.seeds-{int(seed_ids[0]):04d}-{int(seed_ids[-1]):04d}.npz':
    raise ValueError('noncontiguous or incorrectly named seed chunk')
   for s,v in zip(seed_ids,embeddings):
    if int(s) in seen: raise ValueError('Duplicate seed')
    seen[int(s)]=v
 if sorted(seen)!=list(range(1,repetitions+1)): raise ValueError('Missing seeds; cannot silently publish partial ensemble')
 x=np.hstack([seen[s] for s in range(1,repetitions+1)])
 np.save(f'{a.config}.embedding.npy',x)
 from sklearn.metrics import pairwise_distances
 d=pairwise_distances(x.astype(np.float64),metric='euclidean',n_jobs=1); np.fill_diagonal(d,0)
 np.save(f'{a.config}.distances.npy',d)
 write_json(f'{a.config}.ensemble.json',{'config_id':a.config,'run_sha256':lineage,
            'shape':list(x.shape),'embedding_sha256':sha(f'{a.config}.embedding.npy'),'distances_sha256':sha(f'{a.config}.distances.npy')})

def fit_grid(a):
 import hdbscan
 from dimple_representations.hdbscan_runner import estimator_kwargs
 from sklearn.metrics import silhouette_score
 from joblib import Memory
 x=np.load(a.embedding,allow_pickle=False).astype(np.float64); d=np.load(a.distances,allow_pickle=False)
 prepared=load_json(a.manifest); count=prepared['matrix_shape'][0]
 science=manifest_science(prepared); hdb=science['hdbscan']
 lineage=sha(a.manifest)
 if load_json(a.ensemble)!={'config_id':a.config,'run_sha256':lineage,'shape':list(x.shape),
                           'embedding_sha256':sha(a.embedding),'distances_sha256':sha(a.distances)}:
  raise ValueError('ensemble and distances do not match the selected run and configuration')
 if x.ndim!=2 or x.shape[0]!=count or x.shape[1]<1 or d.shape!=(count,count) or not np.isfinite(x).all() or not np.isfinite(d).all():
  raise ValueError('Full ensemble must have valid dimensions and matching finite distances')
 rows=[]; labels=[]; memory=Memory('hdbscan-cache',verbose=0)
 if a.min_samples not in hdb['min_samples']: raise ValueError('Unknown min_samples shard')
 for ordinal,parameters in hdb_candidates(science,a.min_samples):
   t=time.monotonic()
   lab=hdbscan.HDBSCAN(**estimator_kwargs(parameters,core_dist_n_jobs=1),memory=memory).fit_predict(x)
   mask=lab!=-1; k=len(np.unique(lab[mask])); score=None
   if 2<=k<mask.sum(): score=float(silhouette_score(d[np.ix_(mask,mask)],lab[mask],metric='precomputed'))
   rows.append({'config_id':a.config,'candidate_ordinal':ordinal,**parameters,'epsilon':parameters['cluster_selection_epsilon'],'number_of_clusters':k,'number_of_noise_points':int((~mask).sum()),'silhouette':score,'status':'success' if score is not None else 'ineligible','label_row':len(labels),'labels_file':f'{a.config}.ms{a.min_samples:02d}.labels.npz','seconds':time.monotonic()-t})
   labels.append(lab.astype(np.int32)); print(json.dumps(rows[-1]),flush=True)
 pd.DataFrame(rows).to_csv(f'{a.config}.ms{a.min_samples:02d}.metrics.csv',index=False)
 np.savez_compressed(f'{a.config}.ms{a.min_samples:02d}.labels.npz',labels=np.stack(labels),
                     config_id=a.config,min_samples=a.min_samples,run_sha256=lineage)

def score_table(df):
 from freeze5_scoring import legacy_dimple_score
 # Same raw-range/max-divisor formula, explicitly enable noise penalty.
 out,info=legacy_dimple_score(df,fit_include_noise=True)
 out['freeze5_rescaled_score']=out['score']; out['score']=out['raw_score']; out['Score']=out['raw_score']
 # Original notebook does not define tie breaking; stable deterministic order is explicit here.
 out=out.sort_values(['score','config_id','candidate_ordinal'],ascending=[False,True,True],na_position='last',kind='stable')
 return out,info

def read_pool(config_ids, count, lineage, science=None):
 explicit_science=science is not None
 science=science or resolved_science({'configs':[{'config_id':'default'}],'baseline_config_id':'default'})
 hdb=science['hdbscan']
 width=len(list(hdb_candidates(science,hdb['min_samples'][0])))
 tables=[]
 for cid in sorted(config_ids):
  for ms in hdb['min_samples']:
   stem=f'{cid}.ms{ms:02d}'
   csv_name=stem+'.metrics.csv'
   label_name=stem+'.labels.npz'
   frame=pd.read_csv(csv_name, dtype={'config_id':str,'labels_file':str})
   if len(frame)!=width or not frame.config_id.eq(cid).all() or not frame.labels_file.eq(label_name).all():
    raise ValueError('missing or foreign metric rows: '+stem)
   candidates=list(hdb_candidates(science,ms))
   expected=[(ordinal,params['cluster_selection_epsilon'],ms,params['min_cluster_size'],row) for row,(ordinal,params) in enumerate(candidates)]
   cols=['candidate_ordinal','epsilon','min_samples','min_cluster_size','label_row']
   if not all(pd.api.types.is_integer_dtype(frame[k]) for k in cols if k!='epsilon') or list(frame[cols].itertuples(index=False,name=None))!=expected:
    raise ValueError('candidate tuples, ordinals or label rows differ: '+stem)
   if explicit_science:
    for row,(_,parameters) in zip(frame.to_dict('records'),candidates):
     if any(row.get(key)!=value for key,value in parameters.items()): raise ValueError('HDBSCAN candidate parameters differ: '+stem)
   with np.load(label_name,allow_pickle=False) as data:
    if (data['config_id'].item()!=cid or data['min_samples'].item()!=ms or data['run_sha256'].item()!=lineage):
     raise ValueError('foreign label shard: '+stem)
    labels=data['labels']
    if labels.shape!=(width,count) or labels.dtype.kind not in 'iu' or (labels < -1).any():
     raise ValueError('invalid label shard shape or encoding: '+stem)
    for row, assigned in zip(frame.itertuples(index=False),labels):
     mask=assigned!=-1; clusters=np.unique(assigned[mask]).size
     eligible=2<=clusters<mask.sum()
     if (row.number_of_clusters!=clusters or row.number_of_noise_points!=count-mask.sum() or
         row.status!=('success' if eligible else 'ineligible') or
         (eligible and (pd.isna(row.silhouette) or not -1<=row.silhouette<=1)) or
         (not eligible and not pd.isna(row.silhouette))):
      raise ValueError('metrics do not match saved candidate labels: '+stem)
   tables.append(frame)
 if len(list(Path('.').glob('*.metrics.csv')))!=len(tables) or len(list(Path('.').glob('*.labels.npz')))!=len(tables):
  raise ValueError('extra candidate shards')
 return pd.concat(tables,ignore_index=True)

def rank(a):
 g=grid_load(a.grid,a.recipe); science=resolved_science(g); configs={c['config_id']:c for c in science['configs']}
 m=load_json(a.manifest)
 ids=pd.read_csv(a.ids,dtype={'object_id':str},keep_default_na=False)
 if len(ids)!=m['matrix_shape'][0] or list(ids.columns)!=['object_id'] or ids.object_id.duplicated().any() or ids.object_id.eq('').any() or sha(a.grid)!=m['run_grid_sha256'] or sha(a.ids)!=m['object_ids_sha256']:
  raise ValueError('object IDs or grid differ from PREPARE')
 df=read_pool(configs,len(ids),sha(a.manifest),science)
 pooled,info=score_table(df)
 pooled.to_csv('pooled_global_ranked.csv',index=False)
 winners=[]; details={'global':info}; outcomes={}
 def save_winner(row,name,scope):
  with np.load(str(row.labels_file),allow_pickle=False) as z: labels=z['labels'][int(row.label_row)]
  if len(labels)!=len(ids): raise ValueError('Labels/object count mismatch')
  dest=f'{name}.labels.csv'; out=ids.copy(); out['cluster']=labels; out.to_csv(dest,index=False)
  winners.append({'name':name,'selection_scope':scope,'labels_file':dest,**configs[row.config_id],
   'metric':row['metric'],'hdbscan_metric':row['metric'],
   'representation_metric':configs[row.config_id].get('metric','not_applicable'),
   'representation_parameters':json.dumps({k:v for k,v in configs[row.config_id].items() if k!='config_id'},sort_keys=True),
   'hdbscan_parameters':json.dumps({k:(row[k].item() if hasattr(row[k],'item') else row[k]) for k in [*science['hdbscan'],*science['hdbscan_parameters']]},sort_keys=True),
   'backend':science['backend'],**{k:row[k].item() if hasattr(row[k],'item') else row[k] for k in ['candidate_ordinal','epsilon','min_samples','min_cluster_size','score','silhouette','number_of_clusters','number_of_noise_points']}})
 globally_eligible=pooled[pooled.status.eq('success')]
 if not globally_eligible.empty:
  save_winner(globally_eligible.iloc[0],'global_winner','pooled_global')
 for cid,part in df.groupby('config_id'):
  part.to_csv(f'{cid}.grid_results.csv',index=False)
  local,localinfo=score_table(part); local.to_csv(f'{cid}.within_config_ranked.csv',index=False); details[cid]=localinfo
  valid=local[local.status.eq('success')]
  outcomes[cid]='NO_ELIGIBLE_CANDIDATE' if valid.empty else 'ELIGIBLE_CANDIDATES_PRESENT'
  if valid.empty: continue
  save_winner(valid.iloc[0],cid+'_within_best','within_config')
  glob=pooled[(pooled.config_id==cid)&pooled.status.eq('success')].iloc[0]
  save_winner(glob,cid+'_global_best','pooled_global_within_config')
  if cid==science['baseline_config_id']: save_winner(valid.iloc[0],'original_design_baseline','within_original_config')
 winner_fields=['representation_metric','hdbscan_metric','representation_parameters','hdbscan_parameters','backend','name','selection_scope','labels_file','config_id','n_neighbors','min_dist','n_components','densmap','metric',
                'candidate_ordinal','epsilon','min_samples','min_cluster_size','score','silhouette','number_of_clusters','number_of_noise_points']
 pd.DataFrame(winners,columns=winner_fields).to_csv('winners.csv',index=False); write_json('scoring.json',details)
 m.update({'status':'COMPLETE_POOL_NO_ELIGIBLE_CANDIDATE' if globally_eligible.empty else 'COMPLETE_POOL',
  'candidate_rows':len(df),'eligible_rows':len(globally_eligible),'per_config_outcomes':outcomes,
  'tie_break':['score descending','config_id ascending','candidate_ordinal ascending'],'score_column':'raw notebook weighted score; rescaled score supplemental only',
  'silhouette':'all non-noise samples; Euclidean distance on own resolved representation',
  'software_versions':{p:__import__('importlib.metadata',fromlist=['version']).version(p) for p in ['numpy','pandas','scikit-learn','umap-learn','hdbscan']}})
 write_json('run_manifest.json',m)

def evaluate(a):
 from sklearn.metrics import adjusted_rand_score,adjusted_mutual_info_score
 with Path(a.truth).open(encoding='utf-8',newline='') as handle:
  header=next(csv.reader(handle,strict=True),[])
 if len(header)!=2 or header.count('object_id')!=1 or any(not field.strip() for field in header):
  raise ValueError('Truth must have object_id and exactly one target column')
 truth=pd.read_csv(a.truth,dtype={'object_id':str},keep_default_na=False)
 if 'object_id' not in truth: raise ValueError('Truth must have object_id; no positional joins')
 target=[c for c in truth if c!='object_id']
 if len(target)!=1 or truth.object_id.eq('').any() or truth.object_id.duplicated().any() or truth[target[0]].eq('').any(): raise ValueError('Truth must have unique IDs and one nonempty target column')
 rows=[]
 for _,w in pd.read_csv(Path(a.results)/'winners.csv').iterrows():
  if Path(w.labels_file).name!=w.labels_file or not w.labels_file.endswith('.labels.csv'):
   raise ValueError('Invalid winner label filename')
  p=pd.read_csv(Path(a.results)/w.labels_file,dtype={'object_id':str},keep_default_na=False)
  if p.object_id.duplicated().any() or set(p.object_id)!=set(truth.object_id): raise ValueError('Mismatched/duplicate object IDs')
  z=p.merge(truth,on='object_id',validate='one_to_one'); y=z[target[0]]; pred=z.cluster; mask=pred!=-1
  rows.append({'solution':w['name'],'config_id':w.config_id,'selection_scope':w.selection_scope,'ari_all':adjusted_rand_score(y,pred),'ami_all':adjusted_mutual_info_score(y,pred),'ari_assigned':adjusted_rand_score(y[mask],pred[mask]) if mask.sum()>1 else None,'ami_assigned':adjusted_mutual_info_score(y[mask],pred[mask]) if mask.sum()>1 else None,'coverage':float(mask.mean()),'assigned':int(mask.sum()),'total':len(z)})
 result=pd.DataFrame(rows,columns=['solution','config_id','selection_scope','ari_all','ami_all',
                                   'ari_assigned','ami_assigned','coverage','assigned','total'])
 with Path(a.output).open('x',encoding='utf-8',newline='') as output:
  result.to_csv(output,index=False)
 print(result.to_string(index=False))

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('stage', choices=['prepare', 'seeds', 'concat', 'grid', 'rank', 'evaluate'])
    for name in ('grid', 'recipe', 'input', 'source-manifest', 'pixels', 'config', 'embedding',
                 'distances', 'ensemble', 'ids', 'manifest', 'truth', 'results'):
        parser.add_argument('--' + name)
    for name in ('start', 'end', 'min-samples'):
        parser.add_argument('--' + name, type=int)
    parser.add_argument('--image', default='local')
    parser.add_argument('--output', default='external_evaluation.csv')
    args = parser.parse_args()
    {'prepare': prepare, 'seeds': seeds, 'concat': concat, 'grid': fit_grid,
     'rank': rank, 'evaluate': evaluate}[args.stage](args)
if __name__=='__main__': main()
